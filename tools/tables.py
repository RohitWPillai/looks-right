#!/usr/bin/env python3
# What: the results tables quoted in README.md, from the scorer's files: Exp 1's right answers per try under the
#   corrected and the original viscosity key, and on the 10 runs without the disputed pore-push, after the pore-push
#   cause reading (key/pore-push-cause-reading.csv); the means; right per case; the accept-everything baseline.
#   Writes right-per-try.csv, right-per-case.csv and SUMMARY.md.
# Who runs it, from the repository root, after tools/test-a3.py score and score original:
#   python3 tools/tables.py [--scores DIR] [--out DIR]   (both default: results/)
# Refuses: nothing; a try missing from a score file is left out and listed.
import csv
import importlib.util
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location("experiments", ROOT / "tools" / "experiments.py")
experiments = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(experiments)
ARMS = {experiments.LABELS[name]: tries for name, tries in experiments.full_twelve().items()}  # one shared list
KEY = {"density-base": "trusted", "density-push": "untrusted", "slip-base": "untrusted", "slip-push": "not scored",
       "viscosity-base": "untrusted (corrected 9 Oct; trusted before)", "viscosity-push": "untrusted",
       "conductance-base": "trusted", "conductance-push": "untrusted", "pore-base": "trusted",
       "pore-push": "untrusted, for the layering (disputed)", "slab-base": "trusted", "slab-hot": "untrusted"}
VIEWS = {"right_of_10_without_pore_push": "pore-push"}  # view: the case left out


def sections(path):
    out = {}
    for sec in path.read_text().split("\n## ")[1:]:
        name, rows = sec.split("\n", 1)[0].strip(), {}
        for line in sec.splitlines():
            c = [x.strip() for x in line.split("|")[1:-1]]
            if len(c) == 6 and re.match(r"A\d\d$", c[0]):
                rows[c[1]] = {"first": c[2], "run": c[3], "final": c[4].split(" / ")[0], "outcome": c[5]}
        if rows:
            out[name] = rows
    return out


def not_counted():
    with open(ROOT / "key" / "pore-push-cause-reading.csv") as f:
        return {r["try"] for r in csv.DictReader(f) if r["counted"] == "no"}


def right(t, case, row, excluded):
    if row["outcome"] != "right":
        return False
    return not (case == "pore-push" and t in excluded)


def main(scores, out):
    cor, orig = sections(scores / "SCORE.md"), sections(scores / "SCORE-original-key.md")
    excl = not_counted()
    rows, per_try = [], {}
    for arm, tries in ARMS.items():
        for t in tries:
            if t not in cor or t not in orig:
                print(f"missing: {t}", file=sys.stderr)
                continue
            rc = sum(right(t, c, r, excl) for c, r in cor[t].items())
            ro = sum(right(t, c, r, excl) for c, r in orig[t].items())
            na = sum(r["outcome"] == "no answer" for r in cor[t].values())
            named = sum(r["run"] not in ("none", "") and r["first"] != "" for r in cor[t].values())
            views = {v: sum(right(t, c, r, excl) for c, r in cor[t].items() if c != left) for v, left in VIEWS.items()}
            per_try[t] = (rc, ro, views["right_of_10_without_pore_push"])
            rows.append({"experiment": arm, "try": t, "right_of_11_corrected_key": rc, "right_of_11_original_key": ro,
                         **views, "no_answer": na, "runs_named_first_look": named})
    with open(out / "right-per-try.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    cases = sorted(KEY)
    with open(out / "right-per-case.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["case", "right answer (key)"] + list(ARMS))
        for c in cases:
            cells = []
            for tries in ARMS.values():
                have = [t for t in tries if t in cor and c in cor[t]]
                cells.append("not scored" if c == "slip-push" else
                             f"{sum(right(t, c, cor[t][c], excl) for t in have)} of {len(have)}")
            w.writerow([c, KEY[c]] + cells)
    mean = lambda xs: f"{sum(xs) / len(xs):.1f}"
    md = ["# Results summary (generated by tools/tables.py; do not edit)\n",
          "Right answers per try, of the 11 scored runs (slip-push has no fixed answer and is not scored). "
          "Corrected key: viscosity-base untrusted (9 Oct); original key: viscosity-base trusted, as fixed before "
          "9 Oct. After the pore-push cause reading (key/pore-push-cause-reading.csv). Without pore-push: the 11 runs "
          "less the disputed narrow-pore run, corrected key.\n",
          "| arm | tries | right per try, corrected key | mean | right per try, original key | mean | "
          "right per try, without pore-push (of 10) | mean |",
          "|---|---|---|---|---|---|---|---|"]
    for arm, tries in ARMS.items():
        v = [per_try[t] for t in tries if t in per_try]
        if not v:
            continue
        cols = [[x[k] for x in v] for k in range(3)]
        md.append(f"| {arm} | {len(v)} | " + " | ".join(f"{', '.join(map(str, c))} | {mean(c)}" for c in cols) + " |")
    acc_c = sum(KEY[c] == "trusted" for c in cases)
    acc_o = acc_c + 1  # viscosity-base was trusted under the original key
    acc_p = acc_c - (KEY["pore-push"] == "trusted")
    md.append(f"\nAccept everything (plain-code baseline): right on {acc_c} of 11 (corrected key), {acc_o} of 11 "
              f"(original key); without pore-push, {acc_p} of 10.\n")
    md.append("Right per case: `right-per-case.csv`. Per try: `right-per-try.csv`.\n")
    (out / "SUMMARY.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    a = sys.argv
    scores = Path(a[a.index("--scores") + 1]) if "--scores" in a else ROOT / "results"
    out = Path(a[a.index("--out") + 1]) if "--out" in a else ROOT / "results"
    main(scores, out)
